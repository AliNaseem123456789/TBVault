# Deploys the committed code (HEAD) to the EC2 server. Run from your PC for every release:
#   powershell -ExecutionPolicy Bypass -File deploy\deploy.ps1 -Domain tbvault.duckdns.org
#
# What it does:
#   1. First time only: writes backend/.env.production from backend/.env with server values, then stops
#      so you can check it. It is git-ignored and never committed.
#   2. Builds the frontend here (the server only has 1 GB of RAM) with the API at /api.
#   3. Packs backend/ from git HEAD, uploads everything over SSH and runs deploy/server/release.sh,
#      which installs packages, runs database migrations, restarts the API + email worker and
#      rolls back automatically if the new version doesn't start.
# The first deploy also sets the server up (Node, Nginx, Redis, RabbitMQ, swap). -Setup re-runs that.

param(
    [string]$Server = "",
    [string]$Domain = "",
    [string]$KeyFile = (Join-Path $HOME ".ssh\tbvault-key.pem"),
    [switch]$Setup
)

$ErrorActionPreference = "Stop"
$root = Resolve-Path (Join-Path $PSScriptRoot "..")
$backendEnv = Join-Path $root "backend\.env"
$prodEnv = Join-Path $root "backend\.env.production"
$certFile = Join-Path $root "backend\certs\rds-global-bundle.pem"
$tmp = Join-Path $env:TEMP "tbvault-release"

function Check([string]$what) { if ($LASTEXITCODE -ne 0) { throw "$what failed (exit $LASTEXITCODE)" } }

function Read-EnvFile([string]$path) {
    $map = [ordered]@{}
    foreach ($line in Get-Content $path) {
        if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)=(.*)$') { $map[$Matches[1]] = $Matches[2] }
    }
    return $map
}

if (-not $Server) {
    $ipFile = Join-Path $PSScriptRoot ".server-ip"
    if (-not (Test-Path $ipFile)) { throw "No -Server given and deploy/.server-ip not found. Run deploy\create-server.ps1 first." }
    $Server = (Get-Content $ipFile -Raw).Trim()
}
if (-not (Test-Path $KeyFile)) { throw "SSH key not found: $KeyFile" }
$sshArgs = @("-i", $KeyFile, "-o", "StrictHostKeyChecking=accept-new", "-o", "ConnectTimeout=15")
$target = "ubuntu@$Server"

# 1. Server .env
if (-not (Test-Path $prodEnv)) {
    if (-not $Domain) { throw "First deploy: pass -Domain (e.g. -Domain tbvault.duckdns.org) so the server .env can be written." }
    if (-not (Test-Path $backendEnv)) { throw "backend/.env not found" }
    $envMap = Read-EnvFile $backendEnv
    $overrides = [ordered]@{
        NODE_ENV = "production"
        PORT = "3000"
        TRUST_PROXY = "1"
        FRONTEND_URL = "https://$Domain"
        CORS_ORIGINS = "https://$Domain"
        GOOGLE_REDIRECT_URI = "https://$Domain/api/auth/google/callback"
        REDIS_URL = "redis://127.0.0.1:6379"
        # Local broker on the server. For a hosted one (CloudAMQP), put its amqps:// URL here;
        # release.sh then switches the local RabbitMQ off.
        RABBITMQ_URL = "amqp://127.0.0.1:5672"
        DB_SSL_CA_FILE = "./certs/rds-global-bundle.pem"
        S3_ENDPOINT = ""
    }
    foreach ($k in $overrides.Keys) { $envMap[$k] = $overrides[$k] }
    # The server uses its IAM role for S3; local-only settings stay behind.
    foreach ($k in @("S3_ACCESS_KEY_ID", "S3_SECRET_ACCESS_KEY", "MINIO_ENDPOINT", "MINIO_BUCKET", "MINIO_ACCESS_KEY", "MINIO_SECRET_KEY", "TEST_DATABASE_URL", "APP_URL")) {
        $envMap.Remove($k)
    }
    $lines = @("# Server environment for TBVault (generated by deploy.ps1). Git-ignored.") + ($envMap.Keys | ForEach-Object { "$_=$($envMap[$_])" })
    [IO.File]::WriteAllLines($prodEnv, [string[]]$lines, (New-Object Text.UTF8Encoding $false))

    Write-Host "Wrote backend/.env.production. Check it before deploying:" -ForegroundColor Yellow
    Write-Host "  - DATABASE_URL should point at RDS (...rds.amazonaws.com...?sslmode=require)"
    Write-Host "  - STRIPE_WEBHOOK_SECRET must be the secret of a Dashboard webhook for https://$Domain/api/payments/webhook"
    Write-Host "    (the 'stripe listen' secret only works on your PC)"
    Write-Host "  - Add https://$Domain/api/auth/google/callback to your Google OAuth client's redirect URIs"
    Write-Host "Then run this script again."
    exit 0
}
$prodMap = Read-EnvFile $prodEnv
if ($prodMap["DATABASE_URL"] -notmatch "rds\.amazonaws\.com") {
    Write-Host "Warning: DATABASE_URL in .env.production does not look like RDS" -ForegroundColor Yellow
}
if ($prodMap["DB_SSL_CA_FILE"] -and -not (Test-Path $certFile)) {
    throw "backend/certs/rds-global-bundle.pem is missing (setup-rds.ps1 downloads it)"
}

$dirty = git -C $root status --porcelain
if ($dirty) { Write-Host "Note: you have uncommitted changes. Only committed code (HEAD) is deployed." -ForegroundColor Yellow }
$commit = git -C $root rev-parse --short HEAD
Write-Host "Deploying $commit to $Server" -ForegroundColor Cyan

# 2. Frontend build (same origin as the API, so /api)
Push-Location (Join-Path $root "frontend")
try {
    if (-not (Test-Path "node_modules")) { npm ci; Check "npm ci (frontend)" }
    $env:VITE_API_URL = "/api"
    npm run build; Check "frontend build"
} finally {
    Remove-Item Env:VITE_API_URL -ErrorAction SilentlyContinue
    Pop-Location
}

# 3. Package
if (Test-Path $tmp) { Remove-Item -Recurse -Force $tmp }
New-Item -ItemType Directory -Path $tmp | Out-Null
git -C $root archive --format=tar.gz -o (Join-Path $tmp "backend.tgz") HEAD backend; Check "git archive"
tar -czf (Join-Path $tmp "frontend.tgz") -C (Join-Path $root "frontend\dist") .; Check "tar frontend"
Copy-Item $prodEnv (Join-Path $tmp "env")
if (Test-Path $certFile) { Copy-Item $certFile (Join-Path $tmp "rds-global-bundle.pem") }
# Server scripts must have Linux line endings.
Get-ChildItem (Join-Path $PSScriptRoot "server") -File | ForEach-Object {
    $text = [IO.File]::ReadAllText($_.FullName) -replace "`r`n", "`n"
    [IO.File]::WriteAllText((Join-Path $tmp $_.Name), $text, (New-Object Text.UTF8Encoding $false))
}

# 4. Upload and run
Write-Host "Uploading..."
ssh @sshArgs $target "rm -rf /tmp/tbvault-release && mkdir -p /tmp/tbvault-release"; Check "ssh"
scp @sshArgs -q (Get-ChildItem $tmp | ForEach-Object { $_.FullName }) "${target}:/tmp/tbvault-release/"; Check "scp"
Remove-Item -Recurse -Force $tmp

$force = if ($Setup) { "FORCE_SETUP=1 " } else { "" }
ssh @sshArgs $target "sudo ${force}bash /tmp/tbvault-release/release.sh"; Check "release on server"

$site = if ($prodMap["FRONTEND_URL"]) { $prodMap["FRONTEND_URL"] } else { "http://$Server" }
Write-Host ""
Write-Host "Deployed $commit." -ForegroundColor Green
Write-Host "  Site:  $site   (http://$Server works too until HTTPS is on)"
Write-Host "  Logs:  ssh -i $KeyFile $target 'journalctl -u tbvault-api -f'"
